-- Which users have posted the highest number of photos and reels combined? 
-- List the top 5 with their usernames and post counts.

SELECT U.USER_NAME USER_NAME, COUNT(P.POST_ID) POST_COUNT 
FROM USERS U 
JOIN POSTS P ON P.USER_ID = U.USER_ID
WHERE P.PHOTO_ID IS NOT NULL OR P.REEL_ID IS NOT NULL
GROUP BY P.USER_ID
ORDER BY POST_COUNT DESC LIMIT 5;


--  Identify posts that have more comments, more likes, and more bookmarks (high engagement posts).
SELECT DISTINCT(P.POST_ID) POST_IDS, 
	    COUNT(P.POST_ID) POST_COUNT 
FROM POSTS P
LEFT JOIN COMMENTS C ON P.POST_ID = C.POST_ID
LEFT JOIN PHOTO_LIKES PL ON P.POST_ID = PL.POST_ID
LEFT JOIN REEL_LIKES RL ON P.POST_ID = RL.POST_ID
LEFT JOIN BOOKMARKS B ON P.POST_ID = B.POST_ID
WHERE C.COMMENT_ID IS NOT NULL AND 
	  PL.PHOTO_LIKES_ID IS NOT NULL AND
      RL.REEL_LIKES_ID IS NOT NULL AND
      B.BOOKMARKS_ID IS NOT NULL
GROUP BY POST_IDS LIMIT 10;


-- Are there users who have logged in from more than 1 different IP addresses in a single day if nothing captured then show 10 IP entries? 
-- If so, list those users and IPs.

SELECT U.USER_ID USER_ID,
	U.USER_NAME USER_NAME, 
	DATE(L.LOGIN_TIME) LOGIN_DATE,
	COUNT(DISTINCT IP_ADDRESS) UNIQUE_IPS
FROM USERS U
LEFT JOIN LOGIN L ON L.USER_ID = U.USER_ID
GROUP BY USER_ID, LOGIN_DATE
HAVING UNIQUE_IPS>0
LIMIT 10;

