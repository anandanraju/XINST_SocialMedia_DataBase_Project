-- Display the most active user based on total likes (photo + reel) they’ve given.

SELECT USER_ID, COUNT(*) TOTAL_LIKES
FROM (
		SELECT USER_ID FROM PHOTO_LIKES
		UNION ALL 
		SELECT USER_ID FROM REEL_LIKES
) AS ALL_LIKES
GROUP BY USER_ID
ORDER BY TOTAL_LIKES DESC
LIMIT 10;


SELECT 
    USER_ID, 
    MEDIA_TYPE,
    COUNT(*) AS TOTAL_LIKES
FROM (
    SELECT USER_ID, 'Photo' AS MEDIA_TYPE
    FROM PHOTO_LIKES
    UNION ALL
    SELECT USER_ID, 'Reel' AS MEDIA_TYPE
    FROM REEL_LIKES
) AS ALL_LIKES
GROUP BY USER_ID, MEDIA_TYPE
ORDER BY TOTAL_LIKES DESC
LIMIT 10;

-- Find users who have more than 1000 followers but haven't posted anything in the last 60 days.

SELECT 
    U.USER_ID,
    U.USER_NAME,
    COUNT(F.USER_ID) AS FOLLOWERS_COUNT
FROM USERS U
LEFT JOIN FOLLOWS F ON U.USER_ID = F.FOLLOWED_USER_ID
WHERE U.USER_ID NOT IN (
    SELECT DISTINCT USER_ID
    FROM POSTS
    WHERE CREATED_TIME >= NOW() - INTERVAL 60 DAY
)
GROUP BY U.USER_ID, U.USER_NAME
HAVING FOLLOWERS_COUNT > 1000
ORDER BY FOLLOWERS_COUNT DESC;

-- Which location (city) has the highest number of posts, and what's the average number of likes per post in that city?
-- OUTPUT
SELECT 
    P.LOCATION,
    COUNT(P.POST_ID) AS POST_COUNT,
    AVG(COALESCE(PL_LIKES.LIKES, 0) + COALESCE(RL_LIKES.LIKES, 0)) AS AVG_TOTAL_LIKES
FROM POSTS P
LEFT JOIN (
    SELECT POST_ID, COUNT(PHOTO_LIKES_ID) AS LIKES
    FROM PHOTO_LIKES
    GROUP BY POST_ID
) PL_LIKES ON P.POST_ID = PL_LIKES.POST_ID
LEFT JOIN (
    SELECT POST_ID, COUNT(REEL_LIKES_ID) AS LIKES
    FROM REEL_LIKES
    GROUP BY POST_ID
) RL_LIKES ON P.POST_ID = RL_LIKES.POST_ID
GROUP BY P.LOCATION
ORDER BY AVG_TOTAL_LIKES DESC
LIMIT 1;

-- Which location (city) has the highest number of posts, and what's the average number of likes per post in that city?
WITH CITYPOSTS AS (
    SELECT LOCATION, COUNT(*) AS TOTAL_POSTS
    FROM POSTS GROUP BY LOCATION
),
CITYLIKES AS (
    SELECT 
        P.LOCATION,
        COUNT(PL.PHOTO_LIKES_ID) + COUNT(RL.REEL_LIKES_ID) AS TOTAL_LIKES,
        COUNT(DISTINCT P.POST_ID) AS TOTAL_POSTS
    FROM POSTS P
    LEFT JOIN PHOTO_LIKES PL ON P.POST_ID = PL.POST_ID
    LEFT JOIN REEL_LIKES RL ON P.POST_ID = RL.POST_ID
    GROUP BY P.LOCATION
),
TopCity AS (
    SELECT LOCATION FROM CITYPOSTS
    ORDER BY TOTAL_POSTS DESC LIMIT 1
)
SELECT 
    CL.LOCATION, CP.TOTAL_POSTS,
    (CL.TOTAL_LIKES * 1.0 / CP.TOTAL_POSTS) AS AVERAGE_LIKES_PER_POST
FROM TopCity TC
JOIN CITYPOSTS CP ON TC.LOCATION = CP.LOCATION
JOIN CITYLIKES CL ON TC.LOCATION = CL.LOCATION;

-- Find top 10 users who posted a photo and received a comment or like within 5 minutes of posting. 
SELECT DISTINCT P.USER_ID, P.POST_ID, P.CREATED_TIME AS POST_TIME, 
       PL.CREATED_TIME AS LIKE_TIME, PC.SUBMITTED_TIME AS COMMENT_TIME
FROM POSTS P
LEFT JOIN PHOTO_LIKES PL ON P.POST_ID = PL.POST_ID
LEFT JOIN COMMENTS PC ON P.POST_ID = PC.POST_ID
WHERE (
    (PL.CREATED_TIME IS NOT NULL AND TIMESTAMPDIFF(MINUTE, P.CREATED_TIME, PL.CREATED_TIME) <= 5)
    OR
    (PC.SUBMITTED_TIME IS NOT NULL AND TIMESTAMPDIFF(MINUTE, P.CREATED_TIME, PC.SUBMITTED_TIME) <= 5)
)
AND P.PHOTO_ID IS NOT NULL
LIMIT 10;  -- Only photos, not reels






